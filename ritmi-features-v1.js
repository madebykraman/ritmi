(()=>{'use strict';
const S=window.RitmiStorage;
const esc=s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const layer=()=>document.querySelector('#rv-layer');
const close=()=>{const l=layer();if(l)l.innerHTML=''};
const sheet=(title,html)=>{const l=layer();if(!l)return;l.innerHTML=`<div class="rv-backdrop" onclick="RitmiFeature.close()"></div><section class="rv-sheet"><button class="rv-x" onclick="RitmiFeature.close()">Close</button><div class="rv-kicker">Ritmi</div><h2>${esc(title)}</h2>${html}</section>`};
const onboarding=()=>S.snapshot().then(D=>{if(D.onboarded)return;sheet('A quieter way to track','<p>Ritmi is free, local-first and made without an account. Your health data stays in this browser.</p><div class="rv-privacy"><strong>Nothing is required.</strong><br>Start with a period date, add symptoms when useful, and leave everything else alone.</div><button class="rv-primary" onclick="RitmiFeature.finishOnboarding()">Start with Ritmi</button>')});
const finishOnboarding=()=>S.snapshot().then(async D=>{D.onboarded=true;await S.save(D);close()});
const custom=()=>window.RitmiExperience?.customSheet?.();
const add=()=>window.RitmiExperience?.addSignal?.();
const remove=()=>{};
window.RitmiFeature={custom,add,remove,close,onboarding,finishOnboarding};
window.RitmiFeatures=window.RitmiFeatures||{};
window.RitmiFeatures.custom=custom;
window.RitmiFeatures.onboarding=onboarding;
window.RitmiFeatures.finishOnboarding=finishOnboarding;
const boot=()=>setTimeout(()=>{S.snapshot().then(D=>{if(!D.onboarded)onboarding()})},420);
if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',boot);else boot();
})();